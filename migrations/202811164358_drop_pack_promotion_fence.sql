-- DROP-R4a: lease-fenced physical-placement promotion contract.
-- Only a *candidate* book-keeping primitive. No live author/reader route calls
-- this function and SQL cannot independently verify S3/manifest bytes.
-- A future trusted B worker must obtain R3b's complete G proof before
-- opening the finalizing transaction. All tests use disposable PG18 only.

CREATE TABLE free_pack_promotion_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    expected_generation BIGINT NOT NULL CHECK (expected_generation >= 0),
    next_generation BIGINT NOT NULL CHECK (next_generation > expected_generation),
    pack_id BIGINT NOT NULL REFERENCES free_storage_packs(id) ON DELETE RESTRICT,
    expected_content_sha256 BYTEA NOT NULL CHECK (octet_length(expected_content_sha256)=32),
    expected_size_bytes BIGINT NOT NULL CHECK (expected_size_bytes BETWEEN 1 AND 200000),
    expected_pack_sha256 BYTEA NOT NULL CHECK (octet_length(expected_pack_sha256)=32),
    expected_manifest_sha256 BYTEA NOT NULL CHECK (octet_length(expected_manifest_sha256)=32),
    -- The current job's worker must prove exact immutable source inventory
    -- and content-encoding layout. Not an S3 signature or caller capability.
    approved_fingerprint BYTEA NOT NULL CHECK (octet_length(approved_fingerprint)=32),
    lease_epoch BIGINT NOT NULL CHECK (lease_epoch > 0),
    locked_until TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL DEFAULT 'running'
        CHECK (status IN ('running','succeeded','cancelled','failed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    finished_at TIMESTAMPTZ,
    FOREIGN KEY (chapter_id,version_id)
        REFERENCES chapter_versions(chapter_id,id) ON DELETE RESTRICT,
    UNIQUE (chapter_id,version_id,next_generation),
    CHECK (
        (status='succeeded' AND finished_at IS NOT NULL)
        OR (status<>'succeeded' AND finished_at IS NULL)
    )
);
CREATE INDEX free_pack_promotion_jobs_running_idx
    ON free_pack_promotion_jobs(locked_until) WHERE status='running';

-- Every immutable claim except the lease/status is fixed after insertion.
-- Do not let an operator quietly retarget the same job to new chapters,
-- source hashes or physical objects. Lease renewal/reassignment only moves
-- epoch forward, and a completed/cancelled job must never become running.
CREATE FUNCTION guard_free_pack_promotion_job()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'DROP-R4: pack promotion jobs are append-only'
            USING ERRCODE='23514';
    END IF;
    IF NEW.chapter_id<>OLD.chapter_id
        OR NEW.version_id<>OLD.version_id
        OR NEW.expected_generation<>OLD.expected_generation
        OR NEW.next_generation<>OLD.next_generation
        OR NEW.pack_id<>OLD.pack_id
        OR NEW.expected_content_sha256<>OLD.expected_content_sha256
        OR NEW.expected_size_bytes<>OLD.expected_size_bytes
        OR NEW.expected_pack_sha256<>OLD.expected_pack_sha256
        OR NEW.expected_manifest_sha256<>OLD.expected_manifest_sha256
        OR NEW.approved_fingerprint<>OLD.approved_fingerprint
        OR NEW.created_at<>OLD.created_at
        OR NEW.lease_epoch<OLD.lease_epoch
        OR (OLD.status<>'running' AND NEW.status<>OLD.status)
        OR (OLD.status='running' AND NEW.status NOT IN ('running','succeeded','cancelled','failed'))
        OR (OLD.status='running' AND NEW.status='running' AND NEW.finished_at IS NOT NULL)
    THEN
        RAISE EXCEPTION 'DROP-R4: immutable claim or terminal job mutation'
            USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER drop_free_pack_promotion_job_guard
    BEFORE UPDATE OR DELETE ON free_pack_promotion_jobs FOR EACH ROW
    EXECUTE FUNCTION guard_free_pack_promotion_job();

-- A single edition-physical pointer may advance only through a current,
-- unexpired lease and exact source/object receipt. The job lock is taken
-- before the edition lock; every caller must use this consistent order.
-- Old generation and B chapter_publications never change.
CREATE FUNCTION finish_free_pack_promotion(
    p_job_id BIGINT,
    p_epoch BIGINT,
    p_fingerprint BYTEA,
    p_pack_sha BYTEA,
    p_manifest_sha BYTEA
) RETURNS BOOLEAN LANGUAGE plpgsql AS $$
DECLARE
    job free_pack_promotion_jobs%ROWTYPE;
    found_version BIGINT;
    next_ok BOOLEAN;
    changed INTEGER;
BEGIN
    IF p_job_id<=0 OR p_epoch<=0 OR octet_length(p_fingerprint)<>32
        OR octet_length(p_pack_sha)<>32 OR octet_length(p_manifest_sha)<>32
    THEN
        RETURN FALSE;
    END IF;
    SELECT * INTO job FROM free_pack_promotion_jobs
    WHERE id=p_job_id FOR NO KEY UPDATE;
    IF NOT FOUND
        OR job.status<>'running'
        OR job.lease_epoch<>p_epoch
        OR job.locked_until<=clock_timestamp()
        OR job.approved_fingerprint<>p_fingerprint
        OR job.expected_pack_sha256<>p_pack_sha
        OR job.expected_manifest_sha256<>p_manifest_sha
    THEN
        RETURN FALSE;
    END IF;
    SELECT v.id INTO found_version
    FROM chapter_versions v
    JOIN chapters c ON c.id=v.chapter_id
    JOIN books b ON b.id=c.book_id
    WHERE v.chapter_id=job.chapter_id AND v.id=job.version_id
      AND v.content_sha256=job.expected_content_sha256
      AND c.access_level='free' AND c.price_amount=0
      AND NOT c.admin_hold AND NOT c.is_deleted
      AND NOT b.admin_hold AND NOT b.is_deleted
    FOR NO KEY UPDATE OF v;
    IF found_version IS NULL THEN
        RETURN FALSE;
    END IF;
    SELECT EXISTS(
        SELECT 1
        FROM free_edition_storage_generations g
        JOIN free_storage_packs p ON p.id=g.pack_id
        WHERE g.chapter_id=job.chapter_id AND g.version_id=job.version_id
          AND g.generation=job.next_generation AND g.placement_kind='pack'
          AND g.pack_id=job.pack_id
          AND g.content_sha256=job.expected_content_sha256
          AND g.size_bytes=job.expected_size_bytes
          AND p.pack_sha256=p_pack_sha
          AND p.manifest_sha256=p_manifest_sha
    ) INTO next_ok;
    IF NOT next_ok THEN
        RETURN FALSE;
    END IF;
    IF job.expected_generation=0 THEN
        INSERT INTO free_edition_active_storage(chapter_id,version_id,generation)
        VALUES(job.chapter_id,job.version_id,job.next_generation)
        ON CONFLICT(chapter_id,version_id) DO NOTHING;
    ELSE
        UPDATE free_edition_active_storage
        SET generation=job.next_generation,changed_at=clock_timestamp()
        WHERE chapter_id=job.chapter_id AND version_id=job.version_id
          AND generation=job.expected_generation;
    END IF;
    GET DIAGNOSTICS changed = ROW_COUNT;
    IF changed<>1 THEN
        RETURN FALSE;
    END IF;
    UPDATE free_pack_promotion_jobs
    SET status='succeeded',finished_at=clock_timestamp()
    WHERE id=p_job_id AND status='running' AND lease_epoch=p_epoch
      AND locked_until>clock_timestamp();
    GET DIAGNOSTICS changed = ROW_COUNT;
    IF changed<>1 THEN
        RAISE EXCEPTION 'DROP-R4: promotion lease expired during transaction'
            USING ERRCODE='23514';
    END IF;
    RETURN TRUE;
END;
$$;
REVOKE ALL ON FUNCTION finish_free_pack_promotion(BIGINT,BIGINT,BYTEA,BYTEA,BYTEA)
    FROM PUBLIC;
COMMENT ON FUNCTION finish_free_pack_promotion(BIGINT,BIGINT,BYTEA,BYTEA,BYTEA) IS
    'DROP-R4a inactive internal candidate CAS; requires external R3b G readback and actor/job proof.';
