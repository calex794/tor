-- DROP-R2: additive physical placement generations for S349 FREE editions.
-- No historical body migration, no reader routing change and no paid-text changes.
-- Existing free_chapter_storage_objects remains the canonical SINGLE receipt.
-- PACK rows are inert until a separately verified B/G publisher and C gateway exist.

CREATE TABLE free_storage_packs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket TEXT NOT NULL CHECK (
        bucket ~ '^[a-z][a-z0-9-]{1,61}[a-z0-9]$'
        AND bucket NOT LIKE 'public%'
    ),
    object_key TEXT NOT NULL UNIQUE CHECK (
        char_length(object_key) BETWEEN 32 AND 240
        AND object_key ~ '^private/free-packs/[A-Za-z0-9_./-]+[.]zst$'
        AND position('//' in object_key) = 0
        AND object_key !~ '(^|/)[.][.]?(/|$)'
    ),
    pack_sha256 BYTEA NOT NULL CHECK (octet_length(pack_sha256)=32),
    manifest_key TEXT NOT NULL UNIQUE CHECK (
        char_length(manifest_key) BETWEEN 42 AND 260
        AND manifest_key=regexp_replace(object_key,'[.]zst$','.manifest.json')
        AND manifest_key ~ '^private/free-packs/[A-Za-z0-9_./-]+[.]manifest[.]json$'
    ),
    manifest_sha256 BYTEA NOT NULL CHECK (octet_length(manifest_sha256)=32),
    manifest_bytes BIGINT NOT NULL CHECK (manifest_bytes BETWEEN 1 AND 1048576),
    pack_bytes BIGINT NOT NULL CHECK (pack_bytes BETWEEN 26 AND 16777216),
    seek_table_start BIGINT NOT NULL CHECK (
        seek_table_start BETWEEN 1 AND pack_bytes - 25
    ),
    verified_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TRIGGER drop_free_storage_pack_immutable
    BEFORE UPDATE OR DELETE ON free_storage_packs FOR EACH ROW
    EXECUTE FUNCTION reject_free_chapter_storage_change();

-- The same immutable B edition may retain multiple physical generations.
-- The first generation is a verified SINGLE reference; later ones may refer
-- to independently verified PACK frames. Rows are immutable forever: an
-- active switch NEVER destroys the prior generation or any free saved V1.
CREATE TABLE free_edition_storage_generations (
    chapter_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    generation BIGINT NOT NULL CHECK (generation > 0),
    placement_kind TEXT NOT NULL CHECK (placement_kind IN ('single','pack')),
    content_sha256 BYTEA NOT NULL CHECK (octet_length(content_sha256)=32),
    size_bytes BIGINT NOT NULL CHECK (size_bytes BETWEEN 1 AND 200000),
    pack_id BIGINT REFERENCES free_storage_packs(id) ON DELETE RESTRICT,
    frame_offset BIGINT,
    frame_bytes BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (chapter_id, version_id, generation),
    FOREIGN KEY (chapter_id, version_id)
        REFERENCES chapter_versions(chapter_id,id) ON DELETE RESTRICT,
    CHECK (
        (placement_kind='single'
            AND pack_id IS NULL AND frame_offset IS NULL AND frame_bytes IS NULL)
        OR
        (placement_kind='pack' AND pack_id IS NOT NULL
            AND frame_offset IS NOT NULL AND frame_bytes IS NOT NULL
            AND frame_offset BETWEEN 0 AND 16777216
            AND frame_bytes BETWEEN 1 AND 204096
            AND frame_offset + frame_bytes <= 16777216)
    )
);
CREATE INDEX free_edition_storage_generations_pack_idx
    ON free_edition_storage_generations(pack_id) WHERE pack_id IS NOT NULL;

CREATE FUNCTION guard_free_edition_storage_generation()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    pack_end BIGINT;
BEGIN
    -- B's identity and digest are authoritative; G is only a placement.
    IF NOT EXISTS (
        SELECT 1 FROM chapter_versions v
        JOIN chapters c ON c.id=v.chapter_id
        WHERE v.chapter_id=NEW.chapter_id AND v.id=NEW.version_id
          AND v.content_sha256=NEW.content_sha256
          AND c.access_level='free' AND c.price_amount=0
    ) THEN
        RAISE EXCEPTION 'DROP: placement must match immutable free edition'
            USING ERRCODE='23514';
    END IF;
    IF NEW.placement_kind='single' THEN
        IF NOT EXISTS (
            SELECT 1 FROM free_chapter_storage_objects f
            WHERE f.chapter_id=NEW.chapter_id AND f.version_id=NEW.version_id
              AND f.sha256=NEW.content_sha256
              AND f.size_bytes=NEW.size_bytes
        ) THEN
            RAISE EXCEPTION 'DROP: single placement requires exact existing S349 receipt'
                USING ERRCODE='23514';
        END IF;
    ELSE
        -- Serialize same-pack writes with NO KEY UPDATE (compatible with
        -- the FK's KEY SHARE), to prevent concurrent overlapping frames.
        SELECT seek_table_start INTO pack_end
        FROM free_storage_packs WHERE id=NEW.pack_id FOR NO KEY UPDATE;
        IF pack_end IS NULL OR NEW.frame_offset + NEW.frame_bytes > pack_end THEN
            RAISE EXCEPTION 'DROP: frame exceeds pack payload boundary'
                USING ERRCODE='23514';
        END IF;
        IF EXISTS (
            SELECT 1 FROM free_edition_storage_generations g
            WHERE g.pack_id=NEW.pack_id AND g.placement_kind='pack'
              AND int8range(g.frame_offset, g.frame_offset + g.frame_bytes, '[)')
                  && int8range(NEW.frame_offset, NEW.frame_offset + NEW.frame_bytes, '[)')
        ) THEN
            RAISE EXCEPTION 'DROP: packed edition frames overlap'
                USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER drop_free_edition_storage_generation_verified
    BEFORE INSERT ON free_edition_storage_generations FOR EACH ROW
    EXECUTE FUNCTION guard_free_edition_storage_generation();
CREATE TRIGGER drop_free_edition_storage_generation_immutable
    BEFORE UPDATE OR DELETE ON free_edition_storage_generations FOR EACH ROW
    EXECUTE FUNCTION reject_free_chapter_storage_change();

-- No rows are created by migration. Until a later C/G cutover, the existing
-- S349 SINGLE source stays authoritative even when this table is populated.
CREATE TABLE free_edition_active_storage (
    chapter_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    generation BIGINT NOT NULL CHECK (generation > 0),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (chapter_id, version_id),
    FOREIGN KEY (chapter_id, version_id, generation)
        REFERENCES free_edition_storage_generations(chapter_id,version_id,generation)
        ON DELETE RESTRICT
);
CREATE FUNCTION guard_free_edition_active_storage()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'DROP: active generation cannot be deleted'
            USING ERRCODE='23514';
    END IF;
    IF TG_OP='UPDATE' AND (
        NEW.chapter_id <> OLD.chapter_id OR NEW.version_id <> OLD.version_id
        OR NEW.generation <= OLD.generation
    ) THEN
        RAISE EXCEPTION 'DROP: physical placement generation must advance'
            USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER drop_free_edition_active_storage_guard
    BEFORE UPDATE OR DELETE ON free_edition_active_storage FOR EACH ROW
    EXECUTE FUNCTION guard_free_edition_active_storage();

-- Atomic edition-local compare-and-swap. Lock the exact immutable edition
-- first to serialize two competing FIRST promotions (no pointer row yet).
-- This helper is not called from any live HTTP route in DROP-R2.
CREATE FUNCTION promote_free_edition_storage(
    p_chapter_id BIGINT, p_version_id BIGINT,
    p_expected_generation BIGINT, p_next_generation BIGINT
) RETURNS BOOLEAN LANGUAGE plpgsql AS $$
DECLARE
    found_edition BIGINT;
    affected INTEGER;
BEGIN
    IF p_chapter_id <= 0 OR p_version_id <= 0
        OR p_expected_generation < 0
        OR p_next_generation <= p_expected_generation
    THEN
        RETURN FALSE;
    END IF;
    SELECT v.id INTO found_edition
    FROM chapter_versions v
    WHERE v.chapter_id=p_chapter_id AND v.id=p_version_id
    FOR NO KEY UPDATE;
    IF found_edition IS NULL THEN
        RETURN FALSE;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM free_edition_storage_generations g
        WHERE g.chapter_id=p_chapter_id AND g.version_id=p_version_id
          AND g.generation=p_next_generation
    ) THEN
        RETURN FALSE;
    END IF;
    IF p_expected_generation=0 THEN
        INSERT INTO free_edition_active_storage(chapter_id,version_id,generation)
        VALUES (p_chapter_id,p_version_id,p_next_generation)
        ON CONFLICT (chapter_id,version_id) DO NOTHING;
    ELSE
        UPDATE free_edition_active_storage
        SET generation=p_next_generation, changed_at=clock_timestamp()
        WHERE chapter_id=p_chapter_id AND version_id=p_version_id
          AND generation=p_expected_generation;
    END IF;
    GET DIAGNOSTICS affected = ROW_COUNT;
    RETURN affected=1;
END;
$$;
COMMENT ON TABLE free_edition_active_storage IS
    'DROP-R2: inactive candidate catalog only; S349 reader and publication do not consult it.';
COMMENT ON TABLE free_storage_packs IS
    'DROP-R2: immutable private PACK metadata, not independent proof of S3 bytes or entitlement.';
