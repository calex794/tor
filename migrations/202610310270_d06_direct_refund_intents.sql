-- D-06: inert direct-purchase refund and exchange prerequisites.
-- No approved policy exists; checkout deliberately leaves these NULL.
-- Historical purchases are immutable, so legacy terms cannot be backfilled.
ALTER TABLE chapter_purchase_facts
  ADD COLUMN refund_policy_version TEXT,
  ADD COLUMN refund_deadline_at TIMESTAMPTZ,
  ADD CONSTRAINT d06_direct_refund_terms_pair CHECK (
    (refund_policy_version IS NULL AND refund_deadline_at IS NULL)
    OR (
      refund_policy_version IS NOT NULL
      AND char_length(refund_policy_version) BETWEEN 1 AND 80
      AND refund_policy_version = btrim(refund_policy_version)
      AND refund_deadline_at IS NOT NULL
      AND refund_deadline_at >= acquired_at
    )
  );

-- A pending request is NOT a successful refund or a right to refund.
-- Not wired to HTTP until purchase-time policy and the verified first-grant
-- barrier are available in the same trusted financial decision transaction.
CREATE TABLE finance_direct_refund_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  request_key TEXT NOT NULL CHECK (char_length(request_key) = 43),
  request_digest BYTEA NOT NULL CHECK (octet_length(request_digest) = 32),
  reason TEXT NOT NULL CHECK (
    char_length(reason) BETWEEN 1 AND 2000 AND reason=btrim(reason)
  ),
  state TEXT NOT NULL DEFAULT 'pending'
    CHECK (state IN ('pending','processing','approved','rejected')),
  decision_actor_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  decision_reason TEXT CHECK (
    decision_reason IS NULL OR (char_length(decision_reason) BETWEEN 1 AND 1000
                               AND decision_reason=btrim(decision_reason))
  ),
  decided_at TIMESTAMPTZ,
  decision_reference TEXT UNIQUE CHECK (
    decision_reference IS NULL OR
    char_length(decision_reference) BETWEEN 8 AND 160
  ),
  revision BIGINT NOT NULL DEFAULT 1 CHECK (revision >= 1),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (purchase_id,user_id)
    REFERENCES chapter_purchase_facts(id,user_id) ON DELETE RESTRICT,
  UNIQUE (user_id,request_key),
  CHECK (
    (state IN ('pending','processing')
     AND decided_at IS NULL AND decision_actor_id IS NULL
     AND decision_reference IS NULL AND decision_reason IS NULL)
    OR (state IN ('approved','rejected')
        AND decided_at IS NOT NULL AND decision_actor_id IS NOT NULL
        AND decision_reference IS NOT NULL AND decision_reason IS NOT NULL)
  )
);
CREATE UNIQUE INDEX d06_one_open_direct_refund
  ON finance_direct_refund_requests(purchase_id)
  WHERE state IN ('pending','processing');
CREATE INDEX d06_refunds_by_user_recent
  ON finance_direct_refund_requests(user_id,id DESC);

-- Future decision engine may update only the status/audit fields, once.
-- A database client cannot rewrite ownership, reason, or intent identity.
CREATE FUNCTION d06_guard_direct_refund_request()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'refund request history is immutable' USING ERRCODE='23514';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.state <> 'pending' OR NEW.revision<>1 THEN
      RAISE EXCEPTION 'refund requests must start pending' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.id IS DISTINCT FROM OLD.id
     OR NEW.purchase_id IS DISTINCT FROM OLD.purchase_id
     OR NEW.user_id IS DISTINCT FROM OLD.user_id
     OR NEW.request_key IS DISTINCT FROM OLD.request_key
     OR NEW.request_digest IS DISTINCT FROM OLD.request_digest
     OR NEW.reason IS DISTINCT FROM OLD.reason
     OR NEW.created_at IS DISTINCT FROM OLD.created_at
     OR NEW.revision IS DISTINCT FROM OLD.revision + 1
     OR OLD.state IN ('approved','rejected')
     OR NOT (
       (OLD.state='pending' AND NEW.state IN ('processing','rejected'))
       OR (OLD.state='processing' AND NEW.state IN ('pending','approved','rejected'))
     )
  THEN
    RAISE EXCEPTION 'invalid refund state/identity transition'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER d06_guard_direct_refund_requests
  BEFORE INSERT OR UPDATE OR DELETE ON finance_direct_refund_requests
  FOR EACH ROW EXECUTE FUNCTION d06_guard_direct_refund_request();


-- A policy is never invented from the Python project's seven-day default.
-- Only explicit, versioned finance/legal approval may populate this catalog.
-- The empty catalog and NULL purchase snapshots keep live refunds off.
CREATE TABLE finance_direct_refund_policy_catalog (
  version TEXT PRIMARY KEY CHECK (
    char_length(version) BETWEEN 1 AND 80 AND version=btrim(version)
  ),
  approval_reference TEXT NOT NULL UNIQUE CHECK (
    char_length(approval_reference) BETWEEN 8 AND 160
  ),
  approved_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  approved_at TIMESTAMPTZ NOT NULL,
  effective_at TIMESTAMPTZ NOT NULL,
  window_seconds BIGINT NOT NULL CHECK (window_seconds BETWEEN 1 AND 31536000),
  CHECK (effective_at >= approved_at)
);
CREATE TRIGGER d06_direct_policy_immutable
  BEFORE UPDATE OR DELETE ON finance_direct_refund_policy_catalog
  FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();
-- Refund approval explicitly checks the approved policy catalog; a foreign
-- key here would wrongly disable D-08 test/opt-in purchases with unpublished
-- finance terms. Existing terms do NOT imply legal refund authorization.

-- Both D-08's immutable finance snapshot and the D-06 purchase snapshot
-- must freeze exactly the same legal refund deadline.
CREATE FUNCTION d06_verify_purchase_refund_snapshot()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM chapter_purchase_facts p
    WHERE p.id=NEW.purchase_id
      AND p.refund_policy_version=NEW.refund_policy_version
      AND p.refund_deadline_at=NEW.refund_deadline_at
  ) THEN
    RAISE EXCEPTION 'refund deadline differs from authoritative finance posting'
      USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER d06_finance_refund_snapshot_exact
  AFTER INSERT ON finance_chapter_postings
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION d06_verify_purchase_refund_snapshot();
