-- E-01: canonical comments shared by books and exact chapter editions.
-- The storage schema does not itself authorize access: E-02 must verify A/B/C/D.
CREATE TABLE discussion_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  author_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  book_id BIGINT REFERENCES books(id) ON DELETE CASCADE,
  chapter_id BIGINT,
  version_id BIGINT,
  parent_id BIGINT REFERENCES discussion_comments(id) ON DELETE RESTRICT,
  body TEXT NOT NULL CHECK (
    body = btrim(body) AND char_length(body) BETWEEN 1 AND 2000
    AND position(chr(1) IN body) = 0
  ),
  visibility TEXT NOT NULL DEFAULT 'review'
    CHECK (visibility IN ('review','visible','hidden','deleted')),
  command_key TEXT NOT NULL CHECK (char_length(command_key) = 43),
  command_hash BYTEA NOT NULL CHECK (octet_length(command_hash) = 32),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (
    (book_id IS NOT NULL AND chapter_id IS NULL AND version_id IS NULL)
    OR (book_id IS NULL AND chapter_id IS NOT NULL AND version_id IS NOT NULL)
  ),
  FOREIGN KEY (chapter_id,version_id)
    REFERENCES chapter_versions(chapter_id,id) ON DELETE RESTRICT,
  UNIQUE (author_user_id, command_key)
);
CREATE INDEX discussion_comments_book_visible
  ON discussion_comments(book_id,id DESC)
  WHERE visibility='visible' AND book_id IS NOT NULL;
CREATE INDEX discussion_comments_chapter_visible
  ON discussion_comments(chapter_id,version_id,id DESC)
  WHERE visibility='visible' AND chapter_id IS NOT NULL;

-- An anchor references one immutable version. No quoted paid content is stored.
CREATE TABLE discussion_anchors (
  comment_id BIGINT PRIMARY KEY REFERENCES discussion_comments(id) ON DELETE CASCADE,
  chapter_id BIGINT NOT NULL,
  version_id BIGINT NOT NULL,
  block_key TEXT NOT NULL CHECK (
    char_length(block_key) BETWEEN 1 AND 128
    AND block_key ~ '^[A-Za-z0-9_:-]+$'
  ),
  start_utf16 INTEGER NOT NULL CHECK (start_utf16 >= 0),
  end_utf16 INTEGER NOT NULL CHECK (end_utf16 > start_utf16 AND end_utf16 <= 100000),
  FOREIGN KEY(chapter_id,version_id)
    REFERENCES chapter_versions(chapter_id,id) ON DELETE RESTRICT
);
-- Reject anchors on book comments and on any other chapter edition.
CREATE FUNCTION discussion_anchor_target_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM discussion_comments c
    WHERE c.id=NEW.comment_id
      AND c.chapter_id=NEW.chapter_id
      AND c.version_id=NEW.version_id
  ) THEN
    RAISE EXCEPTION 'anchor does not match the comment edition'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER discussion_anchor_guard
  BEFORE INSERT OR UPDATE ON discussion_anchors
  FOR EACH ROW EXECUTE FUNCTION discussion_anchor_target_guard();

-- Do not allow updates to a comment's identity or version after creation.
CREATE FUNCTION discussion_comment_target_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF ROW(OLD.author_user_id,OLD.book_id,OLD.chapter_id,OLD.version_id,
         OLD.parent_id,OLD.command_key,OLD.command_hash)
     IS DISTINCT FROM
     ROW(NEW.author_user_id,NEW.book_id,NEW.chapter_id,NEW.version_id,
         NEW.parent_id,NEW.command_key,NEW.command_hash)
  THEN
    RAISE EXCEPTION 'comment identity or target is immutable'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER discussion_comment_target_guard
  BEFORE UPDATE ON discussion_comments
  FOR EACH ROW EXECUTE FUNCTION discussion_comment_target_guard();
