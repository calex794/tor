-- Purchased chapter facts are not reader progress and never use current_version_id.
-- There is deliberately no browser endpoint capable of creating these rows.
-- Settlement and accounting must be verified in the future commerce boundary.
CREATE TABLE chapter_purchase_facts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    chapter_id BIGINT NOT NULL REFERENCES chapters(id) ON DELETE RESTRICT,
    version_id BIGINT NOT NULL,
    settlement_reference TEXT NOT NULL UNIQUE
        CHECK (char_length(settlement_reference) BETWEEN 8 AND 160),
    amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    acquired_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, chapter_id, version_id),
    UNIQUE (id, user_id, chapter_id, version_id),
    FOREIGN KEY (chapter_id, version_id)
        REFERENCES chapter_versions (chapter_id, id) ON DELETE RESTRICT
);

-- The pointer is separate from the immutable historical purchase fact.
-- Changes for explicit version upgrades require a future trusted operation.
CREATE TABLE library_purchased_chapters (
    user_id BIGINT NOT NULL,
    chapter_id BIGINT NOT NULL,
    active_version_id BIGINT NOT NULL,
    purchase_id BIGINT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, chapter_id),
    FOREIGN KEY (purchase_id, user_id, chapter_id, active_version_id)
        REFERENCES chapter_purchase_facts (id, user_id, chapter_id, version_id)
        ON DELETE RESTRICT
);
CREATE INDEX library_purchased_recent_idx
    ON library_purchased_chapters (user_id, created_at DESC, chapter_id DESC);

-- The library pointer and purchase fact commit atomically. A second
-- settlement for a still-owned chapter fails rather than granting twice;
-- even concurrent writers cannot produce an orphaned purchase or library row.
CREATE FUNCTION install_purchased_chapter()
RETURNS trigger LANGUAGE plpgsql AS $purchase_grant$
BEGIN
    INSERT INTO library_purchased_chapters
        (user_id, chapter_id, active_version_id, purchase_id)
    VALUES (NEW.user_id, NEW.chapter_id, NEW.version_id, NEW.id);
    RETURN NEW;
END;
$purchase_grant$;
CREATE TRIGGER purchase_facts_create_library
    AFTER INSERT ON chapter_purchase_facts
    FOR EACH ROW EXECUTE FUNCTION install_purchased_chapter();

-- A refund/chargeback revokes the right without erasing historical settlement.
-- This is not a refund/payment processor: only trusted accounting may insert.
CREATE TABLE chapter_purchase_revocations (
    purchase_id BIGINT PRIMARY KEY REFERENCES chapter_purchase_facts(id) ON DELETE RESTRICT,
    reversal_reference TEXT NOT NULL UNIQUE
        CHECK (char_length(reversal_reference) BETWEEN 8 AND 160),
    reason TEXT NOT NULL CHECK (reason IN ('refund', 'chargeback', 'fraud')),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE FUNCTION reject_purchase_history_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'historical purchase and library pointer are immutable without explicit transition'
        USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER purchase_facts_no_mutation
    BEFORE UPDATE OR DELETE ON chapter_purchase_facts
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();
CREATE TRIGGER purchased_library_no_mutation
    BEFORE UPDATE OR DELETE ON library_purchased_chapters
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();
CREATE TRIGGER purchase_revocations_no_mutation
    BEFORE UPDATE OR DELETE ON chapter_purchase_revocations
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();
