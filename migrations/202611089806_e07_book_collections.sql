-- E-07 / S009: collections are social metadata, not book entitlements.
-- Every mutation is owner-bound; public rows have an explicit visibility gate.
CREATE TABLE social_book_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title TEXT NOT NULL CHECK (title=btrim(title) AND char_length(title) BETWEEN 1 AND 160),
    description TEXT NOT NULL DEFAULT '' CHECK (char_length(description)<=2000),
    visibility TEXT NOT NULL DEFAULT 'private'
        CHECK (visibility IN ('private','public')),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision>0),
    request_key TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CHECK (request_key IS NULL OR request_key ~ '^[A-Za-z0-9_-]{43}$')
);
CREATE UNIQUE INDEX social_book_collections_owner_request
    ON social_book_collections(owner_user_id,request_key)
    WHERE request_key IS NOT NULL;
CREATE INDEX social_book_collections_owner_active
    ON social_book_collections(owner_user_id,id DESC) WHERE deleted_at IS NULL;
CREATE INDEX social_book_collections_public_active
    ON social_book_collections(id DESC) WHERE visibility='public' AND deleted_at IS NULL;

CREATE TABLE social_book_collection_items (
    collection_id BIGINT NOT NULL
        REFERENCES social_book_collections(id) ON DELETE CASCADE,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    added_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(collection_id,book_id)
);
CREATE INDEX social_book_collection_items_book
    ON social_book_collection_items(book_id,collection_id);
