-- D owns paid-ad money. This is an ad subledger of the existing RUB wallet,
-- not another wallet or a publicly accessible funding mechanism.
CREATE TABLE finance_ad_intents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_id BIGINT NOT NULL REFERENCES users(id),
    command_key TEXT NOT NULL CHECK(char_length(command_key)=43),
    request_hash BYTEA NOT NULL CHECK(octet_length(request_hash)=32),
    product TEXT NOT NULL CHECK(product IN('daily','chapter')),
    book_id BIGINT NOT NULL REFERENCES books(id),
    offer_id BIGINT NOT NULL,
    offer_revision BIGINT NOT NULL CHECK(offer_revision>0),
    slot TEXT NOT NULL CHECK(slot IN('home_featured','book_detail_related','chapter_end_free')),
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    total_days INTEGER,
    rate_minor BIGINT,
    price_minor BIGINT NOT NULL CHECK(price_minor>0),
    target_units BIGINT NOT NULL CHECK(target_units>0),
    publisher_share_bps INTEGER NOT NULL CHECK(publisher_share_bps BETWEEN 0 AND 10000),
    hold_seconds INTEGER NOT NULL CHECK(hold_seconds BETWEEN 0 AND 31536000),
    daily_cap INTEGER NOT NULL CHECK(daily_cap>=0),
    hourly_cap INTEGER NOT NULL CHECK(hourly_cap>=0),
    session_cap INTEGER NOT NULL CHECK(session_cap>=0),
    terms_version TEXT NOT NULL,
    cancellation_policy TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN('pending','failed','posted')),
    campaign_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(advertiser_id,command_key),
    CHECK((status='posted')=(campaign_id IS NOT NULL)),
    CHECK((product='daily' AND starts_at IS NOT NULL AND ends_at>starts_at
        AND total_days>0 AND rate_minor>0 AND target_units=total_days
        AND price_minor::NUMERIC=rate_minor::NUMERIC*total_days
        AND publisher_share_bps=0 AND hold_seconds=0
        AND cancellation_policy='unused_full_utc_days')
       OR (product='chapter' AND starts_at IS NULL AND ends_at IS NULL
        AND total_days IS NULL AND rate_minor IS NULL AND slot='chapter_end_free'
        AND daily_cap>0 AND hourly_cap>0 AND session_cap>0
        AND cancellation_policy='unused_impressions'))
);
CREATE INDEX finance_ad_pending ON finance_ad_intents(id) WHERE status IN('pending','failed');
ALTER TABLE ad_legacy_campaigns ADD FOREIGN KEY(funding_intent_id)
    REFERENCES finance_ad_intents(id) DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE ad_chapter_campaigns ADD FOREIGN KEY(funding_intent_id)
    REFERENCES finance_ad_intents(id) DEFERRABLE INITIALLY DEFERRED;
CREATE FUNCTION finance_ad_intent_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (to_jsonb(OLD)-'status'-'campaign_id') IS DISTINCT FROM
       (to_jsonb(NEW)-'status'-'campaign_id') OR OLD.status='posted'
       OR NEW.status NOT IN('failed','posted') THEN
        RAISE EXCEPTION 'immutable advertising intent' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER finance_ad_intent_snapshot BEFORE UPDATE ON finance_ad_intents
    FOR EACH ROW EXECUTE FUNCTION finance_ad_intent_immutable();
CREATE TRIGGER finance_ad_intent_no_delete BEFORE DELETE ON finance_ad_intents
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();

ALTER TABLE reader_wallet_entries DROP CONSTRAINT reader_wallet_entries_kind_check,
    DROP CONSTRAINT wallet_entry_direction,
    ADD CONSTRAINT reader_wallet_entries_kind_check CHECK(kind IN(
        'verified_funding','chapter_purchase','chapter_refund','chapter_swap_credit',
        'layer_purchase','creator_earning_credit','creator_payout_debit',
        'ad_funding_debit','ad_refund_credit','ad_publisher_credit')),
    ADD CONSTRAINT wallet_entry_direction CHECK(
        (kind='verified_funding' AND delta_minor>0 AND purchase_id IS NULL AND layer_term_id IS NULL)
        OR (kind='chapter_purchase' AND delta_minor<0 AND purchase_id IS NOT NULL AND layer_term_id IS NULL)
        OR (kind IN('chapter_refund','chapter_swap_credit') AND delta_minor>0 AND purchase_id IS NOT NULL AND layer_term_id IS NULL)
        OR (kind='layer_purchase' AND delta_minor<0 AND purchase_id IS NULL AND layer_term_id IS NOT NULL)
        OR (kind IN('creator_earning_credit','ad_refund_credit','ad_publisher_credit') AND delta_minor>0 AND purchase_id IS NULL AND layer_term_id IS NULL)
        OR (kind IN('creator_payout_debit','ad_funding_debit') AND delta_minor<0 AND purchase_id IS NULL AND layer_term_id IS NULL));

CREATE TABLE finance_ad_funding (
    intent_id BIGINT PRIMARY KEY REFERENCES finance_ad_intents(id),
    advertiser_id BIGINT NOT NULL REFERENCES users(id),
    product TEXT NOT NULL CHECK(product IN('daily','chapter')),
    campaign_id BIGINT NOT NULL,
    budget_minor BIGINT NOT NULL CHECK(budget_minor>0),
    target_units BIGINT NOT NULL CHECK(target_units>0),
    publisher_share_bps INTEGER NOT NULL CHECK(publisher_share_bps BETWEEN 0 AND 10000),
    reserved_units BIGINT NOT NULL DEFAULT 0 CHECK(reserved_units>=0 AND reserved_units<=target_units),
    reserved_minor BIGINT NOT NULL DEFAULT 0 CHECK(reserved_minor>=0),
    settled_minor BIGINT NOT NULL DEFAULT 0 CHECK(settled_minor>=0 AND settled_minor<=reserved_minor),
    publisher_settled_minor BIGINT NOT NULL DEFAULT 0 CHECK(publisher_settled_minor>=0 AND publisher_settled_minor<=settled_minor),
    refunded_minor BIGINT NOT NULL DEFAULT 0 CHECK(refunded_minor>=0),
    wallet_entry_id BIGINT NOT NULL UNIQUE REFERENCES reader_wallet_entries(id),
    status TEXT NOT NULL DEFAULT 'funded' CHECK(status IN('funded','cancelled')),
    funded_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(product,campaign_id),
    CHECK(reserved_minor::NUMERIC=floor(budget_minor::NUMERIC*reserved_units/target_units)),
    CHECK(reserved_minor::NUMERIC+refunded_minor<=budget_minor),
    CHECK(status<>'cancelled' OR (settled_minor=reserved_minor AND settled_minor::NUMERIC+refunded_minor=budget_minor))
);
CREATE INDEX finance_ad_funding_owner ON finance_ad_funding(advertiser_id,intent_id DESC);
CREATE FUNCTION finance_ad_funding_monotonic() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(OLD.intent_id,OLD.advertiser_id,OLD.product,OLD.campaign_id,OLD.budget_minor,
           OLD.target_units,OLD.publisher_share_bps,OLD.wallet_entry_id,OLD.funded_at)
       IS DISTINCT FROM
       ROW(NEW.intent_id,NEW.advertiser_id,NEW.product,NEW.campaign_id,NEW.budget_minor,
           NEW.target_units,NEW.publisher_share_bps,NEW.wallet_entry_id,NEW.funded_at)
       OR OLD.status='cancelled' OR NEW.reserved_units<OLD.reserved_units
       OR NEW.reserved_minor<OLD.reserved_minor OR NEW.settled_minor<OLD.settled_minor
       OR NEW.publisher_settled_minor<OLD.publisher_settled_minor OR NEW.refunded_minor<OLD.refunded_minor
    THEN RAISE EXCEPTION 'immutable ad funding or non-monotonic accounting' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER finance_ad_funding_guard BEFORE UPDATE ON finance_ad_funding
    FOR EACH ROW EXECUTE FUNCTION finance_ad_funding_monotonic();
CREATE TRIGGER finance_ad_funding_no_delete BEFORE DELETE ON finance_ad_funding
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();

CREATE TABLE finance_ad_transactions (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    identity TEXT NOT NULL UNIQUE CHECK(char_length(identity) BETWEEN 8 AND 160),
    intent_id BIGINT NOT NULL REFERENCES finance_ad_funding(intent_id) DEFERRABLE INITIALLY DEFERRED,
    operation TEXT NOT NULL CHECK(operation IN('fund','reserve','settle','refund','publisher_mature','publisher_credit')),
    amount_minor BIGINT NOT NULL CHECK(amount_minor>=0),
    wallet_entry_id BIGINT UNIQUE REFERENCES reader_wallet_entries(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE finance_ad_entries (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL REFERENCES finance_ad_transactions(id),
    account TEXT NOT NULL CHECK(account IN('wallet','escrow','reserved','publisher_pending','publisher_available','platform')),
    owner_user_id BIGINT REFERENCES users(id),
    delta_minor BIGINT NOT NULL CHECK(delta_minor<>0),
    UNIQUE NULLS NOT DISTINCT(transaction_id,account,owner_user_id),
    CHECK((account IN('wallet','publisher_pending','publisher_available'))=(owner_user_id IS NOT NULL))
);
CREATE INDEX finance_ad_entries_owner ON finance_ad_entries(owner_user_id,transaction_id DESC);
CREATE TRIGGER finance_ad_transactions_immutable BEFORE UPDATE OR DELETE ON finance_ad_transactions
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();
CREATE TRIGGER finance_ad_entries_immutable BEFORE UPDATE OR DELETE ON finance_ad_entries
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();

CREATE TABLE finance_ad_cancellations (
    intent_id BIGINT PRIMARY KEY REFERENCES finance_ad_funding(intent_id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    command_key TEXT NOT NULL CHECK(char_length(command_key)=43),
    expected_revision BIGINT NOT NULL CHECK(expected_revision>0),
    reason TEXT NOT NULL CHECK(char_length(reason) BETWEEN 1 AND 500),
    refunded_minor BIGINT NOT NULL CHECK(refunded_minor>=0),
    transaction_id BIGINT NOT NULL UNIQUE REFERENCES finance_ad_transactions(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(actor_id,command_key)
);
CREATE TRIGGER finance_ad_cancel_immutable BEFORE UPDATE OR DELETE ON finance_ad_cancellations
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();

CREATE TABLE finance_ad_publisher_balances (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    pending_minor BIGINT NOT NULL DEFAULT 0 CHECK(pending_minor>=0),
    available_minor BIGINT NOT NULL DEFAULT 0 CHECK(available_minor>=0),
    credited_minor BIGINT NOT NULL DEFAULT 0 CHECK(credited_minor>=0)
);
CREATE TABLE finance_ad_publisher_credits (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    intent_id BIGINT NOT NULL REFERENCES finance_ad_funding(intent_id),
    publisher_id BIGINT NOT NULL REFERENCES users(id),
    settlement_transaction_id BIGINT NOT NULL UNIQUE REFERENCES finance_ad_transactions(id),
    amount_minor BIGINT NOT NULL CHECK(amount_minor>0),
    clear_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN('pending','available','credited')),
    maturity_transaction_id BIGINT UNIQUE REFERENCES finance_ad_transactions(id),
    wallet_entry_id BIGINT UNIQUE REFERENCES reader_wallet_entries(id),
    credited_at TIMESTAMPTZ,
    CHECK((wallet_entry_id IS NULL)=(credited_at IS NULL)),
    CHECK((status='credited')=(wallet_entry_id IS NOT NULL)),
    CHECK((status='pending')=(maturity_transaction_id IS NULL))
);
CREATE INDEX finance_ad_maturity ON finance_ad_publisher_credits(publisher_id,clear_at,id)
    WHERE status='pending';
CREATE INDEX finance_ad_available ON finance_ad_publisher_credits(publisher_id,id) WHERE status='available';
CREATE FUNCTION finance_ad_publisher_credit_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(OLD.id,OLD.intent_id,OLD.publisher_id,OLD.settlement_transaction_id,OLD.amount_minor,OLD.clear_at)
       IS DISTINCT FROM ROW(NEW.id,NEW.intent_id,NEW.publisher_id,NEW.settlement_transaction_id,NEW.amount_minor,NEW.clear_at)
       OR OLD.clear_at>clock_timestamp() OR NOT (
           (OLD.status='pending' AND NEW.status='available' AND NEW.maturity_transaction_id IS NOT NULL)
           OR (OLD.status='available' AND NEW.status='credited' AND NEW.wallet_entry_id IS NOT NULL
               AND NEW.credited_at IS NOT NULL AND OLD.maturity_transaction_id=NEW.maturity_transaction_id)
       )
    THEN RAISE EXCEPTION 'immutable or immature publisher credit' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER finance_ad_publisher_credit_guard BEFORE UPDATE ON finance_ad_publisher_credits
    FOR EACH ROW EXECUTE FUNCTION finance_ad_publisher_credit_immutable();
CREATE TRIGGER finance_ad_publisher_credit_no_delete BEFORE DELETE ON finance_ad_publisher_credits
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();
