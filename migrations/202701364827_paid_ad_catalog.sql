-- ADS-01/02/05: two separate prepaid products. No offers or flags are enabled.
CREATE TABLE ad_daily_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    current_revision BIGINT NOT NULL CHECK(current_revision>0),
    enabled BOOLEAN NOT NULL DEFAULT false,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE ad_daily_offer_revisions (
    offer_id BIGINT NOT NULL REFERENCES ad_daily_offers(id),
    revision BIGINT NOT NULL CHECK(revision>0),
    slot TEXT NOT NULL CHECK(slot IN('home_featured','book_detail_related','chapter_end_free')),
    rate_minor BIGINT NOT NULL CHECK(rate_minor>0),
    currency CHAR(3) NOT NULL DEFAULT 'RUB' CHECK(currency='RUB'),
    min_days INTEGER NOT NULL CHECK(min_days>0),
    max_days INTEGER NOT NULL CHECK(max_days>=min_days AND max_days<=366),
    cancellation_policy TEXT NOT NULL CHECK(cancellation_policy='unused_full_utc_days'),
    daily_cap INTEGER NOT NULL CHECK(daily_cap>0),
    hourly_cap INTEGER NOT NULL CHECK(hourly_cap>0 AND hourly_cap<=daily_cap),
    session_cap INTEGER NOT NULL CHECK(session_cap>0 AND session_cap<=daily_cap),
    min_interval_seconds INTEGER NOT NULL CHECK(min_interval_seconds BETWEEN 0 AND 3600),
    terms_version TEXT NOT NULL CHECK(char_length(terms_version) BETWEEN 1 AND 120),
    published_by BIGINT NOT NULL REFERENCES users(id),
    published_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY(offer_id,revision)
);
ALTER TABLE ad_daily_offers ADD FOREIGN KEY(id,current_revision)
    REFERENCES ad_daily_offer_revisions(offer_id,revision) DEFERRABLE INITIALLY DEFERRED;
CREATE TRIGGER ad_daily_offer_revision_immutable BEFORE UPDATE OR DELETE
    ON ad_daily_offer_revisions FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();

CREATE TABLE ad_packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    current_revision BIGINT NOT NULL CHECK(current_revision>0),
    enabled BOOLEAN NOT NULL DEFAULT false,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE ad_package_revisions (
    package_id BIGINT NOT NULL REFERENCES ad_packages(id),
    revision BIGINT NOT NULL CHECK(revision>0),
    price_minor BIGINT NOT NULL CHECK(price_minor>0),
    price_micros_at_offer NUMERIC(30,0) NOT NULL,
    target_impressions BIGINT NOT NULL CHECK(target_impressions>0),
    publisher_share_bps INTEGER NOT NULL CHECK(publisher_share_bps BETWEEN 0 AND 10000),
    currency CHAR(3) NOT NULL DEFAULT 'RUB' CHECK(currency='RUB'),
    pricing_algorithm TEXT NOT NULL CHECK(pricing_algorithm='cumulative_minor_v1'),
    hold_seconds INTEGER NOT NULL CHECK(hold_seconds BETWEEN 0 AND 31536000),
    daily_cap INTEGER NOT NULL CHECK(daily_cap>0),
    hourly_cap INTEGER NOT NULL CHECK(hourly_cap>0 AND hourly_cap<=daily_cap),
    session_cap INTEGER NOT NULL CHECK(session_cap>0 AND session_cap<=daily_cap),
    terms_version TEXT NOT NULL CHECK(char_length(terms_version) BETWEEN 1 AND 120),
    published_by BIGINT NOT NULL REFERENCES users(id),
    published_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY(package_id,revision),
    CHECK(price_micros_at_offer=price_minor::NUMERIC*10000)
);
ALTER TABLE ad_packages ADD FOREIGN KEY(id,current_revision)
    REFERENCES ad_package_revisions(package_id,revision) DEFERRABLE INITIALLY DEFERRED;
CREATE TRIGGER ad_package_revision_immutable BEFORE UPDATE OR DELETE
    ON ad_package_revisions FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();

CREATE TABLE ad_legacy_campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_id BIGINT NOT NULL REFERENCES users(id),
    book_id BIGINT NOT NULL REFERENCES books(id),
    offer_id BIGINT NOT NULL,
    offer_revision BIGINT NOT NULL,
    slot TEXT NOT NULL CHECK(slot IN('home_featured','book_detail_related','chapter_end_free')),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    total_days INTEGER NOT NULL CHECK(total_days BETWEEN 1 AND 366),
    prepaid_days INTEGER NOT NULL CHECK(prepaid_days=total_days),
    rate_minor BIGINT NOT NULL CHECK(rate_minor>0),
    price_minor BIGINT NOT NULL CHECK(price_minor>0),
    funding_intent_id BIGINT NOT NULL UNIQUE,
    status TEXT NOT NULL CHECK(status IN('funded','paused','cancelling','cancelled','completed')),
    revision BIGINT NOT NULL DEFAULT 1 CHECK(revision>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY(offer_id,offer_revision) REFERENCES ad_daily_offer_revisions(offer_id,revision),
    CHECK(ends_at>starts_at AND ends_at=starts_at+total_days*INTERVAL '24 hours'),
    CHECK(price_minor::NUMERIC=rate_minor::NUMERIC*total_days),
    CHECK(starts_at=date_trunc('day',starts_at AT TIME ZONE 'UTC') AT TIME ZONE 'UTC')
);
CREATE INDEX ad_daily_serving ON ad_legacy_campaigns(slot,starts_at,ends_at,id)
    WHERE status='funded';
CREATE INDEX ad_daily_owner ON ad_legacy_campaigns(advertiser_id,id DESC);
CREATE INDEX ad_daily_book_period ON ad_legacy_campaigns(book_id,slot,starts_at,ends_at);

CREATE TABLE ad_chapter_campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_id BIGINT NOT NULL REFERENCES users(id),
    promoted_book_id BIGINT NOT NULL REFERENCES books(id),
    package_id BIGINT NOT NULL,
    package_revision BIGINT NOT NULL,
    funding_intent_id BIGINT NOT NULL UNIQUE,
    status TEXT NOT NULL CHECK(status IN('funded','paused','cancelling','cancelled','completed')),
    revision BIGINT NOT NULL DEFAULT 1 CHECK(revision>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY(package_id,package_revision) REFERENCES ad_package_revisions(package_id,revision)
);
CREATE INDEX ad_chapter_owner ON ad_chapter_campaigns(advertiser_id,id DESC);
CREATE INDEX ad_chapter_funded ON ad_chapter_campaigns(id) WHERE status='funded';

CREATE FUNCTION ad_campaign_snapshot_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (to_jsonb(OLD)-'status'-'revision') IS DISTINCT FROM
       (to_jsonb(NEW)-'status'-'revision') OR NEW.revision<>OLD.revision+1
       OR NOT (
           (OLD.status='funded' AND NEW.status IN('paused','cancelling','completed'))
           OR (OLD.status='paused' AND NEW.status IN('funded','cancelling'))
           OR (OLD.status='completed' AND NEW.status='cancelling')
           OR (OLD.status='cancelling' AND NEW.status='cancelled')
       ) THEN
        RAISE EXCEPTION 'immutable advertising purchase or invalid transition' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER ad_daily_snapshot BEFORE UPDATE ON ad_legacy_campaigns
    FOR EACH ROW EXECUTE FUNCTION ad_campaign_snapshot_immutable();
CREATE TRIGGER ad_daily_no_delete BEFORE DELETE ON ad_legacy_campaigns
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();
CREATE TRIGGER ad_chapter_snapshot BEFORE UPDATE ON ad_chapter_campaigns
    FOR EACH ROW EXECUTE FUNCTION ad_campaign_snapshot_immutable();
CREATE TRIGGER ad_chapter_no_delete BEFORE DELETE ON ad_chapter_campaigns
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();

-- An operator must explicitly publish paid placement policy. Empty means none.
CREATE TABLE ad_slot_policies (
    slot TEXT PRIMARY KEY CHECK(slot IN('home_featured','book_detail_related','chapter_end_free')),
    paid_first BOOLEAN NOT NULL,
    daily_enabled BOOLEAN NOT NULL,
    chapter_enabled BOOLEAN NOT NULL CHECK(NOT chapter_enabled OR slot='chapter_end_free'),
    max_cards INTEGER NOT NULL CHECK(max_cards BETWEEN 1 AND 4),
    revision BIGINT NOT NULL CHECK(revision>0),
    updated_by BIGINT NOT NULL REFERENCES users(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
