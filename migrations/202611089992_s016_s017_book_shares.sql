-- S016/S017: direct friend-to-friend book recommendations; no reading rights.
CREATE TABLE social_book_shares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id > 0),
    sender_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    recipient_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    message TEXT NOT NULL DEFAULT '' CHECK(char_length(message) <= 500),
    command_key TEXT NOT NULL CHECK(command_key ~ '^[A-Za-z0-9_-]{43}$'),
    state TEXT NOT NULL DEFAULT 'delivered'
        CHECK(state IN ('delivered','hidden','reported','muted')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CHECK(sender_user_id <> recipient_user_id),
    UNIQUE(sender_user_id, command_key)
);
CREATE INDEX social_book_shares_inbox
    ON social_book_shares(recipient_user_id, id DESC) WHERE state='delivered';
CREATE INDEX social_book_shares_sender_rate
    ON social_book_shares(sender_user_id, created_at DESC);
CREATE INDEX social_book_shares_receiver_rate
    ON social_book_shares(recipient_user_id, created_at DESC);

CREATE TABLE social_book_share_mutes (
    recipient_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    sender_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    muted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY(recipient_user_id, sender_user_id),
    CHECK(recipient_user_id <> sender_user_id)
);

CREATE TABLE social_book_share_reports (
    share_id BIGINT PRIMARY KEY REFERENCES social_book_shares(id) ON DELETE RESTRICT,
    reporter_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reason TEXT NOT NULL CHECK(reason IN ('spam','abuse','other')),
    details TEXT NOT NULL DEFAULT '' CHECK(char_length(details) <= 500),
    state TEXT NOT NULL DEFAULT 'pending'
        CHECK(state IN ('pending','reviewed','dismissed')),
    reported_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX social_book_share_reports_pending
    ON social_book_share_reports(reported_at, share_id) WHERE state='pending';
