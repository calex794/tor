-- D-05 / I: versioned book packages and discrete paid access terms.
-- New schema only: no historical migration checksum or existing direct V1 changed.
CREATE TABLE commerce_layers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title TEXT NOT NULL CHECK (title=btrim(title) AND char_length(title) BETWEEN 1 AND 120),
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active','hidden','blocked')),
    current_version_id BIGINT,
    current_offer_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX commerce_layers_by_owner ON commerce_layers(owner_user_id,id);

-- Composition changes produce a new immutable snapshot. They do not mutate
-- paid history, and never fan out authoritative grants to all subscribers.
CREATE TABLE commerce_layer_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layer_id BIGINT NOT NULL REFERENCES commerce_layers(id) ON DELETE RESTRICT,
    version_no BIGINT NOT NULL CHECK (version_no>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(layer_id,version_no),
    UNIQUE(layer_id,id)
);
CREATE TABLE commerce_layer_version_books (
    layer_version_id BIGINT NOT NULL
        REFERENCES commerce_layer_versions(id) ON DELETE RESTRICT,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    PRIMARY KEY(layer_version_id,book_id)
);
CREATE INDEX commerce_layer_version_books_by_book
    ON commerce_layer_version_books(book_id,layer_version_id);

CREATE TABLE commerce_layer_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layer_id BIGINT NOT NULL REFERENCES commerce_layers(id) ON DELETE RESTRICT,
    revision BIGINT NOT NULL CHECK (revision>0),
    term_kind TEXT NOT NULL CHECK (term_kind IN ('prepaid_30d','lifetime')),
    price_minor BIGINT NOT NULL CHECK (price_minor>0),
    currency CHAR(3) NOT NULL DEFAULT 'RUB' CHECK (currency='RUB'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(layer_id,revision),
    UNIQUE(layer_id,id)
);
ALTER TABLE commerce_layers
    ADD CONSTRAINT commerce_layers_version_same_layer
        FOREIGN KEY(id,current_version_id)
        REFERENCES commerce_layer_versions(layer_id,id) ON DELETE RESTRICT,
    ADD CONSTRAINT commerce_layers_offer_same_layer
        FOREIGN KEY(id,current_offer_id)
        REFERENCES commerce_layer_offers(layer_id,id) ON DELETE RESTRICT;

-- Every renewal is a new immutable purchase/term. Revoking term P1 must not
-- silently revoke term P2 or a separately purchased chapter V1.
CREATE TABLE commerce_layer_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    layer_id BIGINT NOT NULL REFERENCES commerce_layers(id) ON DELETE RESTRICT,
    offer_id BIGINT NOT NULL,
    base_version_id BIGINT NOT NULL,
    -- First version of the same continuously paid entitlement chain.
    -- A new term is a new immutable payment; it is not a new chain on renewal.
    access_origin_version_id BIGINT NOT NULL,
    term_kind TEXT NOT NULL CHECK(term_kind IN ('prepaid_30d','lifetime')),
    amount_minor BIGINT NOT NULL CHECK(amount_minor>0),
    started_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ,
    purchased_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(id,user_id),
    FOREIGN KEY(layer_id,offer_id)
        REFERENCES commerce_layer_offers(layer_id,id) ON DELETE RESTRICT,
    FOREIGN KEY(layer_id,base_version_id)
        REFERENCES commerce_layer_versions(layer_id,id) ON DELETE RESTRICT,
    FOREIGN KEY(layer_id,access_origin_version_id)
        REFERENCES commerce_layer_versions(layer_id,id) ON DELETE RESTRICT,
    CONSTRAINT commerce_layer_term_period CHECK(
        (term_kind='lifetime' AND expires_at IS NULL)
        OR (term_kind='prepaid_30d' AND expires_at > started_at)
    )
);
CREATE INDEX commerce_layer_terms_user_active
    ON commerce_layer_terms(user_id,layer_id,expires_at,started_at);

CREATE TABLE commerce_layer_term_revocations (
    term_id BIGINT PRIMARY KEY REFERENCES commerce_layer_terms(id) ON DELETE RESTRICT,
    reason TEXT NOT NULL CHECK(reason IN ('refund','chargeback','fraud','legal_block')),
    reversal_reference TEXT NOT NULL UNIQUE
        CHECK (char_length(reversal_reference) BETWEEN 8 AND 160),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A command is claimed under (buyer, key) before locking wallet funds.
-- Its result and money entry commit together or not at all.
CREATE TABLE commerce_layer_commands (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    command_key TEXT NOT NULL CHECK(char_length(command_key)=43),
    layer_id BIGINT NOT NULL REFERENCES commerce_layers(id) ON DELETE RESTRICT,
    expected_offer_id BIGINT NOT NULL,
    expected_version_id BIGINT NOT NULL,
    expected_price_minor BIGINT NOT NULL CHECK(expected_price_minor>0),
    term_id BIGINT UNIQUE REFERENCES commerce_layer_terms(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(user_id,command_key),
    FOREIGN KEY(layer_id,expected_offer_id)
        REFERENCES commerce_layer_offers(layer_id,id) ON DELETE RESTRICT,
    FOREIGN KEY(layer_id,expected_version_id)
        REFERENCES commerce_layer_versions(layer_id,id) ON DELETE RESTRICT
);

