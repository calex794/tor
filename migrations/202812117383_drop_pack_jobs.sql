-- DROP-R4a: separate lease-fenced background physical repack jobs.
-- This is not the existing S349 import queue. It does not publish, authorize
-- readers or change the active generation pointer.
CREATE TABLE free_pack_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    approved_fingerprint BYTEA NOT NULL CHECK (octet_length(approved_fingerprint)=32),
    expected_chapter_count INTEGER NOT NULL CHECK (expected_chapter_count BETWEEN 1 AND 4096),
    status TEXT NOT NULL DEFAULT 'pending'
      CHECK (status IN ('pending','running','succeeded','cancelled','failed')),
    lease_epoch BIGINT NOT NULL DEFAULT 0 CHECK (lease_epoch >= 0),
    locked_until TIMESTAMPTZ,
    pack_id BIGINT REFERENCES free_storage_packs(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    finished_at TIMESTAMPTZ,
    UNIQUE (book_id,approved_fingerprint),
    CHECK ((status='succeeded') = (pack_id IS NOT NULL)),
    CHECK (status <> 'running' OR (lease_epoch > 0 AND locked_until IS NOT NULL))
);
CREATE INDEX free_pack_jobs_pending_idx
    ON free_pack_jobs(status,locked_until) WHERE status IN ('pending','running');
COMMENT ON TABLE free_pack_jobs IS
    'DROP-R4a only: independent repack job lease/fingerprint; candidate placements inert to S349 reads.';
