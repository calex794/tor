-- Initial closed-loop RUB wallet purchase. Funding is NOT exposed over HTTP.
-- Book/chapter price_amount is represented here in minor units of RUB.
CREATE TABLE reader_wallet_accounts (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE RESTRICT,
    balance_minor BIGINT NOT NULL DEFAULT 0 CHECK (balance_minor >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'RUB' CHECK (currency = 'RUB')
);

-- A journal debit can only reference a purchase of the same wallet owner.
ALTER TABLE chapter_purchase_facts
    ADD CONSTRAINT chapter_purchase_owner_pair UNIQUE (id, user_id);

-- The immutable money journal is independent from author payout accounting.
-- Credits must originate from a separately verified funding process (not implemented).
CREATE TABLE reader_wallet_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES reader_wallet_accounts(user_id) ON DELETE RESTRICT,
    kind TEXT NOT NULL CHECK (kind IN ('verified_funding', 'chapter_purchase')),
    delta_minor BIGINT NOT NULL CHECK (delta_minor <> 0),
    balance_after_minor BIGINT NOT NULL CHECK (balance_after_minor >= 0),
    reference TEXT NOT NULL UNIQUE CHECK (char_length(reference) BETWEEN 8 AND 160),
    purchase_id BIGINT,
    FOREIGN KEY (purchase_id, user_id)
        REFERENCES chapter_purchase_facts(id, user_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT wallet_entry_direction CHECK (
        (kind = 'chapter_purchase' AND delta_minor < 0 AND purchase_id IS NOT NULL)
        OR (kind = 'verified_funding' AND delta_minor > 0 AND purchase_id IS NULL)
    )
);
CREATE INDEX reader_wallet_entries_by_user ON reader_wallet_entries(user_id, id DESC);

-- The command row is inserted and completed within one transaction. A database
-- rollback leaves no command, wallet debit, ledger entry or purchased version.
CREATE TABLE chapter_purchase_commands (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    command_key TEXT NOT NULL CHECK (char_length(command_key) = 43),
    chapter_id BIGINT NOT NULL REFERENCES chapters(id) ON DELETE RESTRICT,
    expected_version_id BIGINT NOT NULL,
    expected_price_minor BIGINT NOT NULL CHECK (expected_price_minor > 0),
    purchase_id BIGINT UNIQUE REFERENCES chapter_purchase_facts(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, command_key),
    FOREIGN KEY (chapter_id, expected_version_id)
        REFERENCES chapter_versions(chapter_id, id) ON DELETE RESTRICT
);

-- Neither financial history nor wallet debits can be silently rewritten.
CREATE TRIGGER reader_wallet_entries_no_mutation
    BEFORE UPDATE OR DELETE ON reader_wallet_entries
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();
CREATE TRIGGER chapter_purchase_commands_no_delete
    BEFORE DELETE ON chapter_purchase_commands
    FOR EACH ROW EXECUTE FUNCTION reject_purchase_history_mutation();
