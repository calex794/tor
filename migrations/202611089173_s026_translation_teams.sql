-- Additive schema only. Do not apply on retained production databases.
CREATE TABLE translation_teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id > 0),
    owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    name TEXT NOT NULL CHECK (
        char_length(name) BETWEEN 1 AND 100 AND name = btrim(name)
    ),
    description TEXT NOT NULL DEFAULT ''
        CHECK(char_length(description) <= 2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(id,owner_user_id)
);
CREATE UNIQUE INDEX translation_teams_owner_name_unique
    ON translation_teams(owner_user_id,lower(name));
CREATE INDEX translation_teams_owner_recent
    ON translation_teams(owner_user_id,id DESC);
