-- BKR-86: initial read-only public chapter model.
-- These flags are stronger than a public visibility value.
ALTER TABLE books ADD COLUMN admin_hold BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE books ADD COLUMN is_deleted BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE chapters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    chapter_no INTEGER NOT NULL CHECK (chapter_no > 0),
    title TEXT NOT NULL
        CHECK (title = btrim(title) AND char_length(title) BETWEEN 1 AND 200),
    visibility TEXT NOT NULL DEFAULT 'draft'
        CHECK (visibility IN ('draft', 'public')),
    access_level TEXT NOT NULL DEFAULT 'free'
        CHECK (access_level IN ('free', 'paid')),
    admin_hold BOOLEAN NOT NULL DEFAULT FALSE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    reader_released_at TIMESTAMPTZ,
    UNIQUE (book_id, chapter_no)
);

-- Version bodies are immutable once created: publishing moves the pointer,
-- not the chapter text. Publisher/editor writes are not part of BKR-86.
CREATE TABLE chapter_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    chapter_id BIGINT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
    version_no INTEGER NOT NULL CHECK (version_no > 0),
    body_markdown TEXT NOT NULL CHECK (char_length(body_markdown) <= 50000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (chapter_id, version_no),
    UNIQUE (chapter_id, id)
);

-- Published versions can only be added, never edited in place.
-- Purging old data requires a separate explicit retention policy.
CREATE FUNCTION reject_chapter_version_update()
RETURNS trigger
LANGUAGE plpgsql AS $chapter_version_update$
BEGIN
    RAISE EXCEPTION 'chapter version must be immutable'
        USING ERRCODE = '23514';
END;
$chapter_version_update$;

CREATE TRIGGER chapter_version_reject_update
    BEFORE UPDATE ON chapter_versions
    FOR EACH ROW EXECUTE FUNCTION reject_chapter_version_update();

-- The composite foreign key prevents pointing to another chapter's version.
CREATE TABLE chapter_publications (
    chapter_id BIGINT PRIMARY KEY REFERENCES chapters(id) ON DELETE CASCADE,
    version_id BIGINT NOT NULL,
    published_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (chapter_id, version_id)
        REFERENCES chapter_versions(chapter_id, id) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX chapters_public_book_order_idx
    ON chapters (book_id, chapter_no, id)
    WHERE visibility = 'public' AND access_level = 'free'
      AND NOT admin_hold AND NOT is_deleted;
