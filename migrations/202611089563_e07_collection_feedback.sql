-- S009/E-07: feedback is attached to the collection only, never to entitlements.
-- Ratings and comments require a live user and a currently public collection
-- in the transactional repository; these tables do not grant chapter access.
CREATE TABLE social_book_collection_ratings (
    collection_id BIGINT NOT NULL REFERENCES social_book_collections(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    score SMALLINT NOT NULL CHECK (score BETWEEN 1 AND 5),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (collection_id, user_id)
);

CREATE TABLE social_book_collection_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    collection_id BIGINT NOT NULL REFERENCES social_book_collections(id) ON DELETE CASCADE,
    author_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    body TEXT NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 2000),
    request_key TEXT NOT NULL CHECK (request_key ~ '^[A-Za-z0-9_-]{43}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    UNIQUE (collection_id, author_user_id, request_key)
);
CREATE INDEX social_book_collection_comments_visible
    ON social_book_collection_comments(collection_id, id DESC)
    WHERE deleted_at IS NULL;
