-- Canonical identity belongs to the work and translation language, not a slug.
CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    source_identity TEXT NOT NULL
        CHECK (source_identity = btrim(source_identity) AND source_identity <> ''),
    target_language TEXT NOT NULL
        CHECK (
            target_language ~ '^[a-z0-9][a-z0-9-]*$'
            AND right(target_language, 1) <> '-'
        ),
    title TEXT NOT NULL
        CHECK (title = btrim(title) AND char_length(title) BETWEEN 1 AND 200),
    visibility TEXT NOT NULL DEFAULT 'draft'
        CHECK (visibility IN ('draft', 'public')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_identity, target_language)
);

-- Public reads must never scan drafts just to return a small page.
CREATE INDEX books_public_id_idx ON books (id) WHERE visibility = 'public';
