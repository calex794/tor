-- S033: personal books are private user storage, not drafts of public books.
-- They have no discoverable Book identity, team membership or sharing grants.
CREATE TABLE personal_books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200 AND title = btrim(title)),
    description TEXT NOT NULL DEFAULT '' CHECK (char_length(description) <= 10000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, owner_user_id)
);
CREATE INDEX personal_books_owner_idx ON personal_books (owner_user_id, id DESC);

CREATE TABLE personal_chapters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    book_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    chapter_no INTEGER NOT NULL CHECK (chapter_no > 0),
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200 AND title = btrim(title)),
    content_markdown TEXT NOT NULL CHECK (char_length(content_markdown) <= 500000),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (book_id, owner_user_id) REFERENCES personal_books(id, owner_user_id) ON DELETE CASCADE,
    UNIQUE (book_id, chapter_no)
);
CREATE INDEX personal_chapters_owner_idx
    ON personal_chapters (owner_user_id, book_id, chapter_no);
