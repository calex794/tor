-- DROP-07c: repo-only, additive read-only inventory checkpoints.
-- GREENFIELD TOR: no historical catalogue. Do not deploy or run in production.
-- Checkpoints are audit evidence, never references permitting deletion.
CREATE TABLE free_storage_inventory_cycles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket TEXT NOT NULL CHECK (
        bucket ~ '^[a-z][a-z0-9-]{1,61}[a-z0-9]$'
        AND bucket NOT LIKE 'public%'
    ),
    direction TEXT NOT NULL CHECK (direction IN ('pg_to_s3','s3_to_pg')),
    namespace TEXT NOT NULL CHECK (namespace IN ('single','pack')),
    status TEXT NOT NULL DEFAULT 'running'
        CHECK (status IN ('running','completed','failed')),
    lease_epoch BIGINT NOT NULL DEFAULT 1 CHECK (lease_epoch BETWEEN 1 AND 8),
    locked_until TIMESTAMPTZ,
    page_index BIGINT NOT NULL DEFAULT 0 CHECK (page_index BETWEEN 0 AND 1000000),
    continuation TEXT CHECK (
        continuation IS NULL OR
        (octet_length(continuation) BETWEEN 1 AND 1024
         AND continuation !~ '[[:cntrl:]]')
    ),
    inspected_count BIGINT NOT NULL DEFAULT 0 CHECK (inspected_count >= 0),
    matched_count BIGINT NOT NULL DEFAULT 0 CHECK (matched_count >= 0),
    protected_count BIGINT NOT NULL DEFAULT 0 CHECK (protected_count >= 0),
    unknown_count BIGINT NOT NULL DEFAULT 0 CHECK (unknown_count >= 0),
    mismatch_count BIGINT NOT NULL DEFAULT 0 CHECK (mismatch_count >= 0),
    unverifiable_count BIGINT NOT NULL DEFAULT 0 CHECK (unverifiable_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    completed_at TIMESTAMPTZ,
    failure_code TEXT CHECK (
        failure_code IS NULL OR octet_length(failure_code) BETWEEN 1 AND 48
    ),
    CHECK ((status='running')=(locked_until IS NOT NULL)),
    CHECK ((status IN ('completed','failed'))=(completed_at IS NOT NULL)),
    CHECK (matched_count+protected_count+unknown_count+
           mismatch_count+unverifiable_count=inspected_count)
);
CREATE UNIQUE INDEX free_inventory_one_running_cycle
    ON free_storage_inventory_cycles(bucket,direction,namespace)
    WHERE status='running';

CREATE TRIGGER free_inventory_cycles_no_delete
    BEFORE DELETE ON free_storage_inventory_cycles
    FOR EACH ROW EXECUTE FUNCTION reject_free_chapter_storage_change();

COMMENT ON TABLE free_storage_inventory_cycles IS
    'DROP-07c: lease-fenced, private, operator-only audit pagination. Counts and opaque cursor are NOT proof of orphan status and cannot authorize S3 DELETE.';
