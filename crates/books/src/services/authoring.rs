#[cfg(test)]
mod tests {
    use super::*;
    const KEY: &str = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";

    #[test]
    fn source_language_and_request_key_are_canonical() {
        let book = new_book("  source:123  ", "RU", "  Проба  ", KEY).unwrap();
        assert_eq!(book.target_language, "ru");
        assert_eq!(book.title, "Проба");
        assert!(new_book("source:123", "ru", "Проба", "bad").is_err());
    }

    #[test]
    fn b_01_discovery_metadata_is_bounded_and_canonical() {
        let book = new_book_with_discovery(
            "source:1",
            "ru",
            "Роман",
            KEY,
            "  Автор ",
            " Фантастика, Фэнтези,фантастика",
        )
        .unwrap();
        assert_eq!(book.author_name, "Автор");
        assert_eq!(book.genres, vec!["фантастика", "фэнтези"]);
        assert!(
            new_book_with_discovery("source:1", "ru", "Роман", KEY, "Автор", "Фэнтези,",).is_err()
        );
        assert!(
            new_book_with_discovery("source:1", "ru", "Роман", KEY, &"x".repeat(161), "",).is_err()
        );
        assert!(
            new_book_with_discovery("source:1", "ru", "Роман", KEY, "", &"genre,".repeat(9),)
                .is_err()
        );
        let legacy = new_book("source:1", "ru", "Роман", KEY).unwrap();
        assert!(legacy.author_name.is_empty());
        assert!(legacy.genres.is_empty());
    }

    #[test]
    fn b_01_tags_and_fandoms_are_canonical_and_bounded() {
        let book = new_book_with_taxonomy(
            "source:1",
            "ru",
            "Роман",
            KEY,
            "Автор",
            "Фэнтези",
            TaxonomyFields {
                tags: " Магия, Космос,магия ",
                fandoms: "Наруто, Star Wars",
            },
        )
        .unwrap();
        assert_eq!(book.tags, vec!["магия", "космос"]);
        assert_eq!(book.fandoms, vec!["наруто", "star wars"]);
        assert!(new_book_with_taxonomy(
            "source:1", "ru", "Роман", KEY, "", "",
            TaxonomyFields { tags: "a,", fandoms: "" },
        ).is_err());
        assert!(
            new_book_with_taxonomy("source:1", "ru", "Роман", KEY, "", "",
                TaxonomyFields { tags: "bad\nlabel", fandoms: "" })
                .is_err()
        );
        assert!(new_book_with_taxonomy(
            "source:1",
            "ru",
            "Роман",
            KEY,
            "",
            "",
            TaxonomyFields { tags: "", fandoms: &"a,".repeat(9) },
        )
        .is_err());
        let legacy = new_book_with_discovery("source:1", "ru", "Роман", KEY, "", "").unwrap();
        assert!(legacy.tags.is_empty() && legacy.fandoms.is_empty());
    }

    #[test]
    fn chapter_is_published_on_save_with_a_fixed_maximum_length() {
        fn input(body: &str) -> SaveChapterRequest<'_> {
            SaveChapterRequest {
                book_id: 1,
                chapter_id: None,
                number: 1,
                expected_revision: 0,
                title: "Глава",
                body,
                access: "free",
                price_amount: 0,
                command_key: KEY,
            }
        }
        assert_eq!(
            save_chapter(input(&"я".repeat(50_000)))
                .unwrap()
                .body
                .chars()
                .count(),
            50_000
        );
        assert_eq!(
            save_chapter(input(&"я".repeat(50_001))).unwrap_err(),
            AuthorError::Invalid
        );
        assert!(save_chapter(input("")).is_err());
        assert!(save_chapter(SaveChapterRequest {
            expected_revision: 1,
            ..input("hello")
        })
        .is_err());
        assert_eq!(save_chapter(input("a\r\nb")).unwrap().body, "a\nb");
    }

    #[test]
    fn paid_chapter_requires_a_positive_price() {
        let base = SaveChapterRequest {
            book_id: 1,
            chapter_id: Some(1),
            number: 1,
            expected_revision: 1,
            title: "Глава",
            body: "Текст",
            access: "paid",
            price_amount: 0,
            command_key: KEY,
        };
        assert_eq!(save_chapter(base).unwrap_err(), AuthorError::Invalid);
    }
}
