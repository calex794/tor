//! Validation and outputs for the first authenticated author journey.
#![forbid(unsafe_code)]
use crate::domain::BookKey;
use std::{error::Error, fmt};

#[derive(Debug, Clone, Copy, Eq, PartialEq)]
pub enum AuthorError {
    Invalid,
    Forbidden,
    Missing,
    Conflict,
    Unavailable,
}
impl fmt::Display for AuthorError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{self:?}")
    }
}
impl Error for AuthorError {}

pub fn valid_command_key(key: &str) -> bool {
    key.len() == 43
        && key
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

#[derive(Debug)]
pub struct NewBook {
    pub source_identity: String,
    pub target_language: String,
    pub title: String,
    pub command_key: String,
    pub author_name: String,
    pub genres: Vec<String>,
    pub tags: Vec<String>,
    pub fandoms: Vec<String>,
}

pub fn new_book(
    source: &str,
    language: &str,
    title: &str,
    command_key: &str,
) -> Result<NewBook, AuthorError> {
    let key = BookKey::new(source, language).map_err(|_| AuthorError::Invalid)?;
    let title = title.trim();
    if key.source_identity().chars().count() > 256
        || key.target_language().len() > 32
        || key.source_identity().chars().any(char::is_control)
        || !(1..=200).contains(&title.chars().count())
        || title.chars().any(char::is_control)
        || !valid_command_key(command_key)
    {
        return Err(AuthorError::Invalid);
    }
    Ok(NewBook {
        source_identity: key.source_identity().to_owned(),
        target_language: key.target_language().to_owned(),
        title: title.to_owned(),
        command_key: command_key.to_owned(),
        author_name: String::new(),
        genres: Vec::new(),
        tags: Vec::new(),
        fandoms: Vec::new(),
    })
}

/// B owns canonical author and genre metadata; F only reads it after publication.
pub fn new_book_with_discovery(
    source: &str,
    language: &str,
    title: &str,
    command_key: &str,
    author_name: &str,
    genres: &str,
) -> Result<NewBook, AuthorError> {
    let mut book = new_book(source, language, title, command_key)?;
    let author = author_name.trim();
    if author.chars().count() > 160 || author.chars().any(char::is_control) {
        return Err(AuthorError::Invalid);
    }
    let mut labels = Vec::<String>::new();
    if !genres.trim().is_empty() {
        if genres.chars().count() > 400 {
            return Err(AuthorError::Invalid);
        }
        for item in genres.split(',') {
            if item.chars().any(char::is_control) {
                return Err(AuthorError::Invalid);
            }
            let clean = item
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ")
                .to_lowercase();
            if clean.is_empty() || clean.chars().count() > 40 || clean.chars().any(char::is_control)
            {
                return Err(AuthorError::Invalid);
            }
            if !labels.contains(&clean) {
                labels.push(clean);
            }
            if labels.len() > 8 {
                return Err(AuthorError::Invalid);
            }
        }
    }
    book.author_name = author.to_owned();
    book.genres = labels;
    Ok(book)
}

/// B-owned fields are grouped so creation stays within a bounded contract.
pub struct TaxonomyFields<'a> {
    pub tags: &'a str,
    pub fandoms: &'a str,
}

/// Tags and fandoms are B-owned metadata, never generated by search.
pub fn new_book_with_taxonomy(
    source: &str,
    language: &str,
    title: &str,
    command_key: &str,
    author_name: &str,
    genres: &str,
    taxonomy: TaxonomyFields<'_>,
) -> Result<NewBook, AuthorError> {
    let mut book =
        new_book_with_discovery(source, language, title, command_key, author_name, genres)?;
    book.tags = normalize_taxonomy_labels(taxonomy.tags)?;
    book.fandoms = normalize_taxonomy_labels(taxonomy.fandoms)?;
    Ok(book)
}

/// Canonical, bounded labels match F's catalog faceting contract.
fn normalize_taxonomy_labels(raw: &str) -> Result<Vec<String>, AuthorError> {
    if raw.trim().is_empty() {
        return Ok(Vec::new());
    }
    if raw.chars().count() > 400 {
        return Err(AuthorError::Invalid);
    }
    let mut labels = Vec::<String>::new();
    for value in raw.split(',') {
        let clean = value
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ")
            .to_lowercase();
        if clean.is_empty() || clean.chars().count() > 40 || value.chars().any(char::is_control) {
            return Err(AuthorError::Invalid);
        }
        if !labels.contains(&clean) {
            labels.push(clean);
        }
        if labels.len() > 8 {
            return Err(AuthorError::Invalid);
        }
    }
    Ok(labels)
}

#[derive(Debug, Clone, Copy, Eq, PartialEq)]
pub enum ChapterAccess {
    Free,
    Paid,
}
impl ChapterAccess {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Free => "free",
            Self::Paid => "paid",
        }
    }
}

#[derive(Debug)]
pub struct SaveChapter {
    pub book_id: i64,
    pub chapter_id: Option<i64>,
    pub number: i32,
    pub expected_revision: i64,
    pub title: String,
    pub body: String,
    pub access: ChapterAccess,
    pub price_amount: i64,
    pub command_key: String,
}

pub struct SaveChapterRequest<'a> {
    pub book_id: u64,
    pub chapter_id: Option<u64>,
    pub number: i32,
    pub expected_revision: i64,
    pub title: &'a str,
    pub body: &'a str,
    pub access: &'a str,
    pub price_amount: i64,
    pub command_key: &'a str,
}

pub fn save_chapter(input: SaveChapterRequest<'_>) -> Result<SaveChapter, AuthorError> {
    let book_id = i64::try_from(input.book_id).map_err(|_| AuthorError::Invalid)?;
    let chapter_id = input
        .chapter_id
        .map(|id| i64::try_from(id).map_err(|_| AuthorError::Invalid))
        .transpose()?;
    let title = input.title.trim();
    let body = input.body.replace("\r\n", "\n");
    let access = match input.access {
        "free" => ChapterAccess::Free,
        "paid" => ChapterAccess::Paid,
        _ => return Err(AuthorError::Invalid),
    };
    if book_id <= 0
        || chapter_id.is_some_and(|id| id <= 0)
        || input.number <= 0
        || input.expected_revision < 0
        || (chapter_id.is_none() && input.expected_revision != 0)
        || !(1..=200).contains(&title.chars().count())
        || title.chars().any(char::is_control)
        || !(1..=50_000).contains(&body.chars().count())
        || body.contains('\0')
        || !valid_command_key(input.command_key)
        || match access {
            ChapterAccess::Free => input.price_amount != 0,
            ChapterAccess::Paid => input.price_amount <= 0,
        }
    {
        return Err(AuthorError::Invalid);
    }
    Ok(SaveChapter {
        book_id,
        chapter_id,
        number: input.number,
        expected_revision: input.expected_revision,
        title: title.to_owned(),
        body,
        access,
        price_amount: input.price_amount,
        command_key: input.command_key.to_owned(),
    })
}

