pub mod follow;

use crate::domain::{
    clean_body, valid_html_client_id, valid_key, Conversation, MailError, MessagePage, SentMessage,
};
use async_trait::async_trait;

#[async_trait]
pub trait MailRepository: Send + Sync {
    async fn start(&self, actor: i64, peer: i64) -> Result<i64, MailError>;
    async fn mailbox(
        &self,
        actor: i64,
        after: Option<i64>,
        limit: u16,
    ) -> Result<Vec<Conversation>, MailError>;
    async fn messages(
        &self,
        actor: i64,
        conversation: i64,
        after: Option<i64>,
        before: Option<i64>,
        limit: u16,
    ) -> Result<MessagePage, MailError>;
    async fn send(
        &self,
        actor: i64,
        conversation: i64,
        body: &str,
        key: &str,
    ) -> Result<SentMessage, MailError>;
    async fn send_unkeyed(
        &self,
        actor: i64,
        conversation: i64,
        body: &str,
        receipt_key: &str,
    ) -> Result<SentMessage, MailError>;
    async fn send_html(
        &self,
        actor: i64,
        conversation: i64,
        body: &str,
        client_id: &str,
        key: &str,
    ) -> Result<SentMessage, MailError>;
    async fn set_block(&self, actor: i64, peer: i64, blocked: bool) -> Result<(), MailError>;
}

pub struct MailService<R> {
    repo: R,
}

impl<R: MailRepository> MailService<R> {
    pub fn new(repo: R) -> Self {
        Self { repo }
    }

    pub async fn start(&self, actor: i64, peer: i64) -> Result<i64, MailError> {
        if actor <= 0 || peer <= 0 || actor == peer {
            return Err(MailError::Invalid);
        }
        self.repo.start(actor, peer).await
    }

    pub async fn mailbox(
        &self,
        actor: i64,
        after: Option<i64>,
        limit: u16,
    ) -> Result<Vec<Conversation>, MailError> {
        if actor <= 0 || after.is_some_and(|id| id <= 0) || !(1..=100).contains(&limit) {
            return Err(MailError::Invalid);
        }
        self.repo.mailbox(actor, after, limit).await
    }

    pub async fn messages(
        &self,
        actor: i64,
        conversation: i64,
        after: Option<i64>,
        before: Option<i64>,
        limit: u16,
    ) -> Result<MessagePage, MailError> {
        if actor <= 0
            || conversation <= 0
            || after.is_some_and(|id| id < 0)
            || before.is_some_and(|id| id <= 0)
            || (after.is_some() && before.is_some())
            || !(1..=100).contains(&limit)
        {
            return Err(MailError::Invalid);
        }
        self.repo
            .messages(actor, conversation, after, before, limit)
            .await
    }

    pub async fn send(
        &self,
        actor: i64,
        conversation: i64,
        body: &str,
        key: &str,
    ) -> Result<SentMessage, MailError> {
        if actor <= 0 || conversation <= 0 || !valid_key(key) {
            return Err(MailError::Invalid);
        }
        self.repo
            .send(actor, conversation, &clean_body(body)?, key)
            .await
    }

    /// Source fallback for forms without a client key: same sender/body within 5s.
    /// receipt_key is generated by the adapter, never a client idempotency claim.
    pub async fn send_unkeyed(
        &self,
        actor: i64,
        conversation: i64,
        body: &str,
        receipt_key: &str,
    ) -> Result<SentMessage, MailError> {
        if actor <= 0 || conversation <= 0 || !valid_key(receipt_key) {
            return Err(MailError::Invalid);
        }
        self.repo
            .send_unkeyed(actor, conversation, &clean_body(body)?, receipt_key)
            .await
    }

    pub async fn send_html(
        &self,
        actor: i64,
        conversation: i64,
        body: &str,
        client_id: &str,
        key: &str,
    ) -> Result<SentMessage, MailError> {
        if actor <= 0 || conversation <= 0 || !valid_html_client_id(client_id) || !valid_key(key) {
            return Err(MailError::Invalid);
        }
        self.repo
            .send_html(actor, conversation, &clean_body(body)?, client_id, key)
            .await
    }

    pub async fn send_to_peer(
        &self,
        actor: i64,
        peer: i64,
        body: &str,
        key: &str,
    ) -> Result<SentMessage, MailError> {
        // Validate before creating even an empty conversation.
        let body = clean_body(body)?;
        if !valid_key(key) {
            return Err(MailError::Invalid);
        }
        let conversation = self.start(actor, peer).await?;
        self.send(actor, conversation, &body, key).await
    }

    pub async fn set_block(&self, actor: i64, peer: i64, blocked: bool) -> Result<(), MailError> {
        if actor <= 0 || peer <= 0 || actor == peer {
            return Err(MailError::Invalid);
        }
        self.repo.set_block(actor, peer, blocked).await
    }
}
